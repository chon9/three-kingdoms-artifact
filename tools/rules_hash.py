#!/usr/bin/env python3
"""Regenerates scripts/core/rules/rules_version.gd (docs/design/EFFECT_SYSTEM_SPEC.md §10.2, D10).

    python tools/rules_hash.py           # rewrite the constant
    python tools/rules_hash.py --check   # exit 1 when it is stale

RULES_VERSION is the first 12 hex characters of a SHA-256 over the rules code
and the rules data, so any rules change changes it:
  * every .gd file in scripts/core/rules/ except rules_version.gd itself,
  * scripts/core/match_engine.gd and scripts/core/card_library.gd,
  * data/classic_cards.json and data/training_cards.json (rules live in the card entries).
Files are hashed in sorted path order as "<path>\\n" followed by the content with
CR removed, so Windows (CRLF) and Linux checkouts agree. Exported builds use binary
script tokens and cannot rehash the sources, so the constant is the only runtime
source; tests/rules_schema_test.gd recomputes it and fails when it is stale.
"""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RULES_DIR = "scripts/core/rules"
OUTPUT = RULES_DIR + "/rules_version.gd"
EXTRA = ["scripts/core/match_engine.gd", "scripts/core/card_library.gd",
         "data/classic_cards.json", "data/training_cards.json"]


def rules_files():
    names = sorted(name for name in os.listdir(os.path.join(ROOT, RULES_DIR)) if name.endswith(".gd"))
    files = ["%s/%s" % (RULES_DIR, name) for name in names if "%s/%s" % (RULES_DIR, name) != OUTPUT]
    return sorted(files + EXTRA)


def code_hash():
    digest = hashlib.sha256()
    for path in rules_files():
        with open(os.path.join(ROOT, path), "rb") as handle:
            text = handle.read().decode("utf-8").replace("\r", "")
        digest.update((path + "\n").encode("utf-8"))
        digest.update(text.encode("utf-8"))
    return digest.hexdigest()


def render(full):
    files = ",\n\t".join('"%s"' % path for path in rules_files())
    return (
        "extends RefCounted\n"
        "## Generated by tools/rules_hash.py; do not edit. The version of the rules\n"
        "## code and data (EFFECT_SYSTEM_SPEC.md §10.2, D10): replays and the Steam\n"
        "## content hash carry it, so a rules change never replays or connects\n"
        "## silently. tests/rules_schema_test.gd fails when it is stale.\n"
        "\n"
        "const RULES_VERSION = \"%s\"\n"
        "const CODE_HASH = \"%s\"\n"
        "const FILES = [\n\t%s]\n" % (full[:12], full, files))


def main():
    full = code_hash()
    text = render(full)
    path = os.path.join(ROOT, OUTPUT)
    current = open(path, encoding="utf-8").read().replace("\r", "") if os.path.exists(path) else ""
    if "--check" in sys.argv:
        print("RULES_VERSION %s is %s" % (full[:12], "current" if current == text else "STALE"))
        return 0 if current == text else 1
    if current != text:
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    print("RULES_VERSION %s" % full[:12])
    return 0


if __name__ == "__main__":
    sys.exit(main())
